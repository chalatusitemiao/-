# 生成真实的 .xlsx / .csv 测试文件，用来验证 src/utils/sheet.js 的解析器。
# 用 openpyxl（真实 Excel 文件结构）而不是手搓 XML，
# 否则测的是「我以为 Excel 长什么样」而不是真的 Excel。
#
# 特别注意：购置日期这一列刻意用 datetime 写入，
# 这样 Excel 里存的是「日期序列号 + 单元格格式」，正好覆盖
# 「读出来是数字 44638 而不是 2022-03-18」这个最容易踩的坑。
import os
from datetime import date
from openpyxl import Workbook

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), 'fixtures')
os.makedirs(OUT, exist_ok=True)

HEAD = ['车牌号', '车类型', '载重(吨)', '购置价格(元)', '购置日期', '当前累计里程(km)']


def make(name, headers, rows, sheet='Sheet1', date_col=5):
    wb = Workbook()
    ws = wb.active
    ws.title = sheet
    ws.append(headers)
    for r in rows:
        ws.append(r)
    if date_col:
        for i in range(2, len(rows) + 2):
            ws.cell(row=i, column=date_col).number_format = 'yyyy-mm-dd'
    p = os.path.join(OUT, name)
    wb.save(p)
    print('wrote', name, len(rows), 'rows')


# 1) 标准模板：与页面「下载模板」一致的表头，日期是真日期类型
make(
    'std.xlsx',
    HEAD,
    [
        ['苏E·8K215', '牵引车', 32, 418000, date(2022, 3, 18), 386000],
        ['苏E·6T730', '厢式货车', 10, 253000, date(2024, 5, 9), 128500],
        ['浙B·A12345', '冷藏车', 15, 392000, date(2023, 8, 21), 64500],
        ['皖A·B67890', '自卸车', 30, 386000, date(2021, 1, 30), 210300],
    ],
)

# 2) 表头写法不规范 + 各种脏数据（单位、千分位、简写车型、坏车牌、重复车牌、坏日期）
make(
    'messy.xlsx',
    ['车辆类型', '号牌', '核定载重', '车价', '购买日期', '总里程'],
    [
        ['半挂', '苏E8K215', '32 吨', '¥418,000', '2022-03-18', '386,000 km'],  # 应能被清洗
        ['厢式', '沪D·N78520', '10', '253000', date(2020, 11, 3), 128500],       # 日期是真日期
        ['冷链', '', '15', '392000', '2023-08-21', 64500],                       # 车牌空着 → 报错
        ['牵引车', '苏E8K215', '32', '418000', '2022-03-18', 1],                  # 与第 1 行完全同名 → 重复
        ['', '', '', '', '', ''],                                                # 空行应被跳过
        ['不存在的车型', '浙B·Z99999', '12', '300000', '2020-01-01', 1000],       # 车型不在基准表里 → 仍可导入
        ['牵引车', '苏E·BADD1', '32', '400000', '不是日期', 1000],                # 日期解析不了
        ['牵引车', '苏E·FUTR1', '32', '400000', '2099-01-01', 1000],              # 日期在未来
    ],
    date_col=None,
)

# 3) 第二张工作表在前的情况（sheet 顺序不该影响读取）
wb = Workbook()
ws2 = wb.active
ws2.title = '说明'
ws2['A1'] = '这个文件的第一张表是说明，数据在第二张表'
ws2['A2'] = '解析器只读第一张表，这是已知限制'
ws2b = wb.create_sheet('车辆数据')
ws2b.append(HEAD)
ws2b.append(['苏E·TEST1', '牵引车', 32, 400000, date(2023, 1, 1), 1000])
wb.save(os.path.join(OUT, 'multi.xlsx'))
print('wrote multi.xlsx 2 sheets')

# 4) 只有表头、没有数据行
make('empty.xlsx', HEAD, [])

# 5) 另一份普通文件
make('plain.xlsx', HEAD, [['苏E·INLN1', '平板车', 25, 240000, date(2022, 12, 12), 55555]])

# 6) CSV（带 BOM，Excel 另存为 CSV 的常见形态）
csv_path = os.path.join(OUT, 'std.csv')
with open(csv_path, 'w', encoding='utf-8-sig', newline='') as f:
    f.write(','.join(HEAD) + '\n')
    f.write('苏E·8K215,牵引车,32,418000,2022-03-18,386000\n')
    f.write('苏E·6T730,厢式货车,10,253000,2024-05-09,128500\n')
    f.write('"苏E·QUOT1",牵引车,"32","418,000","2022/3/18","386,000"\n')
print('wrote std.csv')

